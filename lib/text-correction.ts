export function correctText(original: string, scriptText = normalizeInputScripts(original).text) {
  const input = original.trim();
  let text = mapEditableParts(separateIdAction(repairKnownMixedWords(scriptText.trim())), part => {
    return normalizeGameText(part
      .replace(atWord('[\\p{L}]+', 'giu'), token => dictionary[token.toLowerCase()] ? keepCase(token, dictionary[token.toLowerCase()]) : token)
      .replace(new RegExp('(?<![\\p{L}\\p{N}_])(не|я)\\s+магу(?![\\p{L}\\p{N}_])', 'giu'), match => keepCase(match, match.toLowerCase().replace('магу', 'могу')))
      .replace(new RegExp('(?<![\\p{L}\\p{N}_])у\\s+(?:миня|мня)(?![\\p{L}\\p{N}_])', 'giu'), match => keepCase(match, 'у меня'))
      .replace(new RegExp('(?<![\\p{L}\\p{N}_])не\\s+удеться(?![\\p{L}\\p{N}_])', 'giu'), match => keepCase(match, 'не получается'))
      // In a negative ability construction this is «ничего», not an instruction «не чего».
      .replace(atWord('не[ \\t]+чего(?=[ \\t]+не[ \\t]+(?:могу|можем|получается))', 'giu'), match => keepCase(match, 'ничего')))
      .replace(new RegExp('(?<![\\p{L}\\p{N}_])(помогите|помоги)[ \\t]+(пожалуйста)(?![\\p{L}\\p{N}_])', 'giu'), '$1, $2')
      .replace(new RegExp('(?<![\\p{L}\\p{N}_])(пожалуйста)[ \\t]+(?=(?:не|у|я|мне|нам)(?![\\p{L}\\p{N}_]))', 'giu'), '$1, ');
  });
  if (text !== input) {
    let firstPart = true;
    text = mapEditableParts(text, part => {
      if (!firstPart) return part;
      firstPart = false;
      return part.replace(/^[а-яё]/u, first => first.toUpperCase());
    });
  }
  return text;
}
